    /// <summary>生成给前端的 JSON：{ "人设": [["字段名","text","说明"], ...], ... }</summary>
    public static System.Text.Json.Nodes.JsonObject ToJson()
    {
        var obj = new System.Text.Json.Nodes.JsonObject();
        foreach (var sec in Sections)
        {
            var arr = new System.Text.Json.Nodes.JsonArray();
            foreach (var f in Table[sec])
            {
                arr.Add(new System.Text.Json.Nodes.JsonArray(
                    System.Text.Json.Nodes.JsonValue.Create(f.Name),
                    System.Text.Json.Nodes.JsonValue.Create(f.Type),
                    System.Text.Json.Nodes.JsonValue.Create(f.Hint),
                    System.Text.Json.Nodes.JsonValue.Create(f.Mark)));
            }
            obj[sec] = arr;
        }
        return obj;
    }

    /// <summary>新卡默认结构（各字段留空，list 型给空数组）</summary>
    public static System.Text.Json.Nodes.JsonObject NewCard()
    {
        var card = new System.Text.Json.Nodes.JsonObject
        {
            ["_版本"] = 3,
        };
        foreach (var sec in Sections)
        {
            var so = new System.Text.Json.Nodes.JsonObject();
            foreach (var f in Table[sec])
            {
                so[f.Name] = f.Type == "list"
                    ? new System.Text.Json.Nodes.JsonArray()
                    : System.Text.Json.Nodes.JsonValue.Create("");
            }
            card[sec] = so;
        }
        return card;
    }
